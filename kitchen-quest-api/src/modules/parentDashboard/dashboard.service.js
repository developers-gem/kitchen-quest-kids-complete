// GROCERY OVERVIEW
// ---------------------------------------------------------------------------

async function getGroceryOverview(familyId) {
  const list = await groceryService.getOrCreateActiveList(familyId);
  return {
    needed: list.items.filter((i) => !i.checked),
    checked: list.items.filter((i) => i.checked),
    customAdditions: list.items.filter((i) => i.custom),
    byRecipe: summarizeByRecipe(list.items),
  };
}

function summarizeByRecipe(items) {
  const map = new Map();
  items.forEach((item) => {
    (item.sourceRecipes || []).forEach((recipeId) => {
      const key = String(recipeId);
      if (!map.has(key)) map.set(key, []);
      map.get(key).push(item.name);
    });
  });
  return Array.from(map.entries()).map(([recipeId, ingredientNames]) => ({ recipeId, ingredientNames }));
}

// ---------------------------------------------------------------------------
// SETTINGS (read-model; writes reuse the existing users/children endpoints
// so preference logic lives in exactly one place -- see the design doc)
// ---------------------------------------------------------------------------

async function getSettings(user, familyId) {
  const children = await ChildProfile.find({ familyId, deletedAt: null });
  return {
    notificationPreferences: user.notificationPreferences,
    privacy: {
      emailVerified: user.emailVerified,
      accountStatus: user.status,
      dataExportOrDeleteEndpoint: "DELETE /api/v1/users/me",
    },
    children: (Array.isArray(children) ? children : []).map((c) => ({
      _id: c._id,
      displayName: c.displayName,
      accessibilityPreferences: c.preferences?.accessibilityPreferences,
    })),
  };
}

