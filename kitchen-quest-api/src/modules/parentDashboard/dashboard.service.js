// ---------------------------------------------------------------------------

async function getOverview(childId, familyId) {
  const child = await getOwnedChild(childId, familyId);

  const [gameSessions, recipeProgresses, xpTransactions] = await Promise.all([
    GameSession.find({ childProfile: child._id, status: "completed" }),
    RecipeProgress.find({ child: child._id, status: "completed" }),
    XPTransaction.find({ childProfile: child._id }),
  ]);

  const weeklyXpEarned = (Array.isArray(xpTransactions) ? xpTransactions : [])
    .filter((t) => withinLastDays(t.createdAt, 7))
    .reduce((sum, t) => sum + t.amount, 0);

  const totalActivityCount =
    (Array.isArray(gameSessions) ? gameSessions.length : 0) + (Array.isArray(recipeProgresses) ? recipeProgresses.length : 0);

  const recentActivity = await buildRecentActivity(child._id, 10);

  return {
    child: { _id: child._id, displayName: child.displayName, avatarColor: child.avatarColor, currentLevel: child.currentLevel },
    totalActivityCount,
    weeklyXpEarned,
    currentStreak: child.currentStreak,
    longestStreak: child.longestStreak,
    totalXP: child.totalXP,
    recentActivity,
  };
}

async function buildRecentActivity(childId, limit) {
  const [gameSessions, recipeProgresses] = await Promise.all([
    GameSession.find({ childProfile: childId, status: "completed" }),
    RecipeProgress.find({ child: childId, status: "completed" }),
  ]);

  const gameEntries = await Promise.all(
    (Array.isArray(gameSessions) ? gameSessions : []).map(async (s) => {
      const game = await Game.findById(s.game);
      return {
        type: "game",
        title: game ? game.title : "Unknown game",
        date: s.completedAt || s.createdAt,
        xpEarned: s.xpEarned,
        stars: s.stars,
      };
    })
  );

  const recipeEntries = await Promise.all(
    (Array.isArray(recipeProgresses) ? recipeProgresses : []).map(async (p) => {
      const recipe = await Recipe.findById(p.recipe);
      return {
        type: "recipe",
        title: recipe ? recipe.title : "Unknown recipe",
        date: p.completedAt || p.createdAt,
        xpEarned: p.xpEarned,
        pendingParentVerification: recipe ? recipe.requiresParentVerification && !p.parentVerified : false,
      };
    })
  );

  return [...gameEntries, ...recipeEntries]
    .sort((a, b) => new Date(b.date) - new Date(a.date))
    .slice(0, limit);
}

