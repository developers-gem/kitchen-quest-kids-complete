// WEEKLY SUMMARY
// ---------------------------------------------------------------------------

async function getWeeklySummary(childId, familyId) {
  const child = await getOwnedChild(childId, familyId);

  const [gameSessions, recipeProgresses, xpTransactions] = await Promise.all([
    GameSession.find({ childProfile: child._id, status: "completed" }),
    RecipeProgress.find({ child: child._id, status: "completed" }),
    XPTransaction.find({ childProfile: child._id }),
  ]);

  const thisWeekGames = (Array.isArray(gameSessions) ? gameSessions : []).filter((s) =>
    withinLastDays(s.completedAt || s.createdAt, 7)
  );
  const thisWeekRecipes = (Array.isArray(recipeProgresses) ? recipeProgresses : []).filter((p) =>
    withinLastDays(p.completedAt || p.createdAt, 7)
  );
  const allXpTransactions = Array.isArray(xpTransactions) ? xpTransactions : [];
  const thisWeekXpTransactions = allXpTransactions.filter((t) => withinLastDays(t.createdAt, 7));
  const thisWeekXp = thisWeekXpTransactions.reduce((sum, t) => sum + t.amount, 0);

  // FIXED (production readiness audit follow-up): this used to be
  // hardcoded to 0 with a comment saying "NutritionLesson module not
  // built yet" -- that module has since been built (see
  // modules/nutrition/), but this dashboard was never updated to read
  // from it. There's no separate NutritionLessonProgress record with its
  // own timestamp to filter by "this week," so this counts distinct
  // lessons via their XPTransaction (sourceType: "lesson") records
  // created in the last 7 days -- the same source-of-truth pattern the
  // rest of this function already uses for games/recipes/XP.
  const nutritionLessonsCompletedThisWeek = new Set(
    thisWeekXpTransactions.filter((t) => t.sourceType === "lesson").map((t) => String(t.sourceId))
  ).size;

  // "Foods tried" this week: distinct non-optional ingredients across
  // recipes completed this week -- a simple, honest proxy given no
  // separate "food discovery" event exists yet.
  const foodsTriedThisWeek = new Set();
  for (const p of thisWeekRecipes) {
    // eslint-disable-next-line no-await-in-loop
    const recipe = await Recipe.findById(p.recipe);
    if (recipe) recipe.ingredients.filter((i) => !i.optional).forEach((i) => foodsTriedThisWeek.add(i.name));
  }

  return {
    weekRange: { start: new Date(Date.now() - SEVEN_DAYS_MS).toISOString(), end: new Date().toISOString() },
    gamesCompleted: thisWeekGames.length,
    recipesCompleted: thisWeekRecipes.length,
    foodsTried: foodsTriedThisWeek.size,
    nutritionLessonsCompleted: nutritionLessonsCompletedThisWeek,
    totalXPEarned: thisWeekXp,
    currentStreak: child.currentStreak,
  };
}

