const SEVEN_DAYS_MS = 7 * 24 * 60 * 60 * 1000;



/**
 * Date-range filtering is done in application code rather than a Mongo
 * `$gte` query. Two reasons: (1) it keeps this module portable across the
 * real Mongoose model and this codebase's in-memory test fakes, which
 * don't implement range operators; (2) at MVP scale (a handful of
 * sessions per child per week) this is negligible cost. The database
 * architecture doc already flags the production-scale answer: a
 * materialized `WeeklyProgressSummary` regenerated by a nightly job,
 * behind this exact same API contract, so switching later doesn't touch
 * any client code.
 */
function withinLastDays(date, days) {
  if (!date) return false;
  return Date.now() - new Date(date).getTime() <= days * 24 * 60 * 60 * 1000;
}

