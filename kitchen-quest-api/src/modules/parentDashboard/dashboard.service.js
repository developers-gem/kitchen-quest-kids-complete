// LEARNING PROGRESS
// ---------------------------------------------------------------------------

async function getLearningProgress(childId, familyId) {
  const child = await getOwnedChild(childId, familyId);

  const [gameSessions, recipeProgresses] = await Promise.all([
    GameSession.find({ childProfile: child._id, status: "completed" }),
    RecipeProgress.find({ child: child._id, status: "completed" }),
  ]);

  const nutritionTopics = new Set();
  const foodsDiscovered = new Set();
  const cookingSkills = new Set();
  const regionNames = new Set();

  for (const s of Array.isArray(gameSessions) ? gameSessions : []) {
    // eslint-disable-next-line no-await-in-loop
    const game = await Game.findById(s.game);
    if (!game) continue;
    (game.nutritionTopics || []).forEach((t) => nutritionTopics.add(t));
    (game.foodTopics || []).forEach((t) => foodsDiscovered.add(t));
    if (game.state) regionNames.add(game.state);
  }

  for (const p of Array.isArray(recipeProgresses) ? recipeProgresses : []) {
    // eslint-disable-next-line no-await-in-loop
    const recipe = await Recipe.findById(p.recipe);
    if (!recipe) continue;
    (recipe.nutritionLearning || []).forEach((t) => nutritionTopics.add(t));
    (recipe.cookingSkills || []).forEach((s) => cookingSkills.add(s));
    recipe.ingredients.filter((i) => !i.optional).forEach((i) => foodsDiscovered.add(i.name));
  }

  return {
    nutritionTopicsExplored: [...nutritionTopics],
    cookingSkillsLearned: [...cookingSkills],
    foodsDiscovered: [...foodsDiscovered],
    regionsUnlocked: [...regionNames],
  };
}

// ---------------------------------------------------------------------------
// ACTIVITY HISTORY (paginated, merged across types)
// ---------------------------------------------------------------------------

async function getActivityHistory(childId, familyId, query = {}) {
  await getOwnedChild(childId, familyId);
  const { page, limit } = parsePagination(query, { defaultLimit: 15, maxLimit: 50 });

  const all = await buildRecentActivity(childId, 1000); // bounded by realistic per-child volume at MVP scale
  const total = all.length;
  const start = (page - 1) * limit;
  const pageItems = all.slice(start, start + limit);

  return {
    data: {
      games: pageItems.filter((a) => a.type === "game"),
      recipes: pageItems.filter((a) => a.type === "recipe"),
      // Challenges and Achievements modules aren't built yet (see the
      // production audit's roadmap) -- these keys are included now, empty,
      // so a future implementation is additive and never a breaking
      // response-shape change for clients already consuming this endpoint.
      challenges: [],
      achievements: [],
    },
    meta: buildPaginationMeta({ page, limit, total }),
  };
}

